// Measures how tall each showcase card's demo is once it has mounted and settled, on a phone (iPhone 13: 390 px, touch)
// and on a desktop (1440 × 900), and writes src/showcase/cardHeights.ts. A card shows a placeholder of that height until
// its demo mounts (kit.tsx, "Lazy card bodies"), so mounting doesn't move the page. Rerun it after changing how tall a
// demo is (the whole-page CLS check in tests/e2e/page-cls.spec.ts fails when a placeholder is far off):
//   pnpm dev                                   (or: pnpm exec vite build && pnpm exec vite preview)
//   node scripts/card-heights.mjs [url]        (default http://localhost:5173)
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { chromium, devices } from '@playwright/test'
import { root } from './paths.mjs'

const url = process.argv[2] ?? 'http://localhost:5173'
const out = join(root, 'src/showcase/cardHeights.ts')

const browser = await chromium.launch()
const res = {}
for (const [name, opts] of [['phone', devices['iPhone 13']], ['desktop', { viewport: { width: 1440, height: 900 } }]]) {
  const ctx = await browser.newContext({ ...opts, colorScheme: 'light', reducedMotion: 'no-preference' })
  await ctx.addInitScript(() => { try { localStorage.setItem('ui-theme:v1', JSON.stringify({ mode: 'light' })) } catch { /* private mode */ } })
  const page = await ctx.newPage()
  await page.goto(url)
  await page.waitForFunction(() => document.querySelectorAll('[data-spec]').length > 100, null, { timeout: 60_000 })
  // scroll through at a reading pace so every demo mounts the way it does for a reader, then let async demos settle
  const vh = await page.evaluate(() => innerHeight)
  for (let y = 0; y <= await page.evaluate(() => document.documentElement.scrollHeight); y += vh / 2) {
    await page.evaluate(y => scrollTo(0, y), y); await page.waitForTimeout(250)
  }
  await page.waitForTimeout(4000)
  // cards in a grid row stretch to the tallest one, and so would a demo's flex-1 parts: measure each at its own height
  await page.addStyleTag({ content: 'main section > .grid { align-items: start !important }' })
  await page.waitForTimeout(500)
  res[name] = await page.evaluate(() => {
    // the demo's own height: from its first in-flow child's top to its last one's bottom (the body itself is stretched
    // to the card on desktop, so its box says nothing)
    const bodyHeight = body => {
      let top = Infinity, bottom = -Infinity
      for (const c of body.children) {
        const cs = getComputedStyle(c)
        if (cs.position === 'absolute' || cs.position === 'fixed' || cs.display === 'none') continue
        const r = c.getBoundingClientRect()
        top = Math.min(top, r.top - parseFloat(cs.marginTop)); bottom = Math.max(bottom, r.bottom + parseFloat(cs.marginBottom))
      }
      return bottom > top ? Math.round(bottom - top) : 0
    }
    return Object.fromEntries([...document.querySelectorAll('[data-spec]')].map(card => {
      const body = card.querySelector('[data-spec-body]')
      return [card.id, body.querySelector(':scope > [data-spec-hold]') ? null : bodyHeight(body)]
    }))
  })
  await ctx.close()
}
await browser.close()

const ids = Object.keys(res.phone).filter(id => res.phone[id] != null && res.desktop[id] != null).sort()
const missing = Object.keys(res.phone).filter(id => !ids.includes(id))
writeFileSync(out, `// Generated by scripts/card-heights.mjs: don't edit by hand, rerun it after changing how tall a demo is.
// How tall each card's demo is once mounted, so the placeholder a card shows until then is the same size and mounting
// it doesn't move the page (kit.tsx, "Lazy card bodies"). Cards missing here get a typical height for their span.

/** Card id → demo height in px on a phone (iPhone 13, 390 px, touch) and on a desktop (1440 px). */
export const CARD_HEIGHTS: Readonly<Record<string, readonly [phone: number, desktop: number]>> = {
${ids.map(id => `  '${id}': [${res.phone[id]}, ${res.desktop[id]}],`).join('\n')}
}
`)
console.log(`${out}: ${ids.length} cards${missing.length ? `; not measured (never mounted): ${missing.join(', ')}` : ''}`)
